"""Write the TypeScript types of the WebSocket protocol from the pydantic models.

    uv run python -m supportagent.cli.gen_types            # write frontend/src/lib/protocol.ts
    uv run python -m supportagent.cli.gen_types --check    # exit 1 if that file is out of date

The Python models are the source of truth. The frontend never declares an event shape by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from supportagent.api.protocol import CLIENT_ADAPTER
from supportagent.events import EVENT_ADAPTER

DEFAULT_PATH = Path(__file__).resolve().parents[4] / "frontend" / "src" / "lib" / "protocol.ts"

_HEADER = (
    "// Generated by `python -m supportagent.cli.gen_types` from the backend's pydantic models.\n"
    "// Do not edit. Change the models and run the generator again."
)
_PRIMITIVES = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_type(option) for option in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "array":
        inner = _type(schema.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object":
        return "Record<string, unknown>"
    return _PRIMITIVES.get(kind, "unknown")


def _interface(name: str, schema: dict[str, Any], *, all_required: bool) -> str:
    """One interface. The server always sends every field, so its fields are never optional."""
    required = set(schema.get("required", []))
    lines = []
    if description := schema.get("description"):
        lines.append(f"/** {' '.join(description.split())} */")
    lines.append(f"export interface {name} {{")
    for field, spec in schema.get("properties", {}).items():
        optional = "" if all_required or field in required else "?"
        lines.append(f"  {field}{optional}: {_type(spec)};")
    lines.append("}")
    return "\n".join(lines)


def _union(name: str, schema: dict[str, Any]) -> str:
    members = [_type(option) for option in schema["oneOf"]]
    return f"export type {name} =\n" + "\n".join(f"  | {member}" for member in members) + ";"


def render() -> str:
    server, client = EVENT_ADAPTER.json_schema(), CLIENT_ADAPTER.json_schema()
    parts = [_HEADER]
    parts += [_interface(n, s, all_required=True) for n, s in server["$defs"].items()]
    parts.append(_union("ServerEvent", server))
    parts += [_interface(n, s, all_required=False) for n, s in client["$defs"].items()]
    parts.append(_union("ClientMessage", client))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_PATH)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date. Run the generator.", file=sys.stderr)
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
